CREATE TABLE ChuyenPhong (
    MACHUYENPHONG BIGINT AUTO_INCREMENT PRIMARY KEY,
    MADP BIGINT NOT NULL,
    MAPHONGCU VARCHAR(10) NOT NULL,
    MAPHONGMOI VARCHAR(10) NOT NULL,
